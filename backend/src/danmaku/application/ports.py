class CredentialStore(Protocol):
    """Store a secret behind a fresh opaque reference. Missing references resolve to None.

    Implementations translate temporary storage failures to a sanitized retryable error.
    Callers publish a reference only after put succeeds and discard it if publication fails.
    """

    def put(self, secret: SecretStr) -> str: ...
    def get(self, reference: str) -> SecretStr | None: ...
    def delete(self, reference: str) -> None: ...


